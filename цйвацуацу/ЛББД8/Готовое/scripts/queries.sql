-- Задание 3. Стоимость заказа покупателя = кол-во * (материалы по норме расхода + технологические операции)
CREATE VIEW в_стоимость_строки_заказа AS
SELECT col.код_заказа_покупателя, col.номер_строки, p.название AS название_продукции, col.количество,
       COALESCE(mc.затраты,0) AS материалы_на_единицу,
       COALESCE(oc.затраты,0) AS операции_на_единицу,
       ROUND(col.количество * COALESCE(mc.затраты,0), 2) AS стоимость_материалов,
       ROUND(col.количество * COALESCE(oc.затраты,0), 2) AS стоимость_операций,
       ROUND(col.количество * (COALESCE(mc.затраты,0) + COALESCE(oc.затраты,0)), 2) AS полная_стоимость
FROM строка_заказа_покупателя col
JOIN номенклатура p ON p.код_номенклатуры = col.код_продукции
LEFT JOIN спецификация s ON s.код_продукции = col.код_продукции
LEFT JOIN (SELECT sm.код_спецификации, SUM(sm.количество * ip.значение_цены) AS затраты
           FROM спецификация_материал sm JOIN цена ip ON ip.код_номенклатуры = sm.код_материала
           GROUP BY sm.код_спецификации) mc ON mc.код_спецификации = s.код_спецификации
LEFT JOIN (SELECT so.код_спецификации, SUM(so.количество * ip.значение_цены) AS затраты
           FROM спецификация_операция so JOIN цена ip ON ip.код_номенклатуры = so.код_операции
           GROUP BY so.код_спецификации) oc ON oc.код_спецификации = s.код_спецификации;

CREATE VIEW в_стоимость_заказа AS
SELECT co.код_заказа_покупателя, co.номер, co.дата_заказа,
       ROUND(SUM(lc.стоимость_материалов),2)  AS стоимость_материалов,
       ROUND(SUM(lc.стоимость_операций),2) AS стоимость_операций,
       ROUND(SUM(lc.полная_стоимость),2)     AS полная_стоимость
FROM заказ_покупателя co JOIN в_стоимость_строки_заказа lc ON lc.код_заказа_покупателя = co.код_заказа_покупателя
GROUP BY co.код_заказа_покупателя, co.номер, co.дата_заказа;

-- Единый запрос задания 3, сохранённый как представление
CREATE VIEW запрос_полная_стоимость_заказа AS
SELECT  з.номер                                   AS номер_заказа,
        з.дата_заказа                             AS дата_заказа,
        к.наименование                            AS заказчик,
        ROUND(SUM(с.количество * (
            COALESCE((SELECT SUM(см.количество * ц.значение_цены)      -- материалы на 1 шт. (норма расхода * цена)
                      FROM спецификация сп
                      JOIN спецификация_материал см ON см.код_спецификации = сп.код_спецификации
                      JOIN цена ц                   ON ц.код_номенклатуры  = см.код_материала
                      WHERE сп.код_продукции = с.код_продукции), 0)
          + COALESCE((SELECT SUM(со.количество * ц.значение_цены)      -- технологические операции на 1 шт.
                      FROM спецификация сп
                      JOIN спецификация_операция со ON со.код_спецификации = сп.код_спецификации
                      JOIN цена ц                   ON ц.код_номенклатуры  = со.код_операции
                      WHERE сп.код_продукции = с.код_продукции), 0)
        )), 2)                                    AS полная_стоимость
FROM    заказ_покупателя з
JOIN    строка_заказа_покупателя с ON с.код_заказа_покупателя = з.код_заказа_покупателя
JOIN    контрагент к               ON к.код_контрагента = з.код_заказчика
GROUP BY з.код_заказа_покупателя, з.номер, з.дата_заказа, к.наименование;
